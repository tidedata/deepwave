//! Per-stage timings of the certificate check (run: zig build test -Dlane=bls -Doptimize=ReleaseFast
//! with ZUI_BLS_MICROBENCH=1). Not a conformance bench; for finding where time goes.
const std = @import("std");
const field = @import("field.zig");
const tower = @import("tower.zig");
const curve = @import("curve.zig");
const encoding = @import("encoding.zig");
const h2c = @import("hash_to_curve.zig");
const pairing = @import("pairing.zig");
const sig = @import("sig.zig");
const Fp = field.Fp;

fn now() u64 {
    var ts: std.posix.timespec = undefined;
    _ = std.posix.system.clock_gettime(.MONOTONIC, &ts);
    return @as(u64, @intCast(ts.sec)) * 1_000_000_000 + @as(u64, @intCast(ts.nsec));
}

fn report(name: []const u8, n: usize, t0: u64) void {
    const dt = now() - t0;
    std.debug.print("{s:<28} {d:>10.1} ns\n", .{ name, @as(f64, @floatFromInt(dt)) / @as(f64, @floatFromInt(n)) });
}

test "microbench" {
    if (std.c.getenv("ZUI_BLS_MICROBENCH") == null) return;
    var x = curve.g1_generator.x;
    const y = curve.g1_generator.y;
    var t0 = now();
    const n = 1_000_000;
    for (0..n) |_| x = x.mul(y);
    report("fp mul", n, t0);
    t0 = now();
    for (0..n) |_| x = x.sqr();
    report("fp sqr", n, t0);
    t0 = now();
    for (0..n) |_| x = x.mulPortable(y);
    report("fp mul portable", n, t0);
    t0 = now();
    for (0..n) |_| x = Fp.redc(Fp.mulWide(x.l, y.l));
    report("fp mulWide+redc", n, t0);
    t0 = now();
    for (0..n) |_| x = Fp.redc(Fp.sqrWide(x.l));
    report("fp sqrWide+redc", n, t0);
    t0 = now();
    for (0..n) |_| x = Fp.redc(Fp.mulWidePortable(x.l, y.l));
    report("fp mulWidePortable+redc", n, t0);
    t0 = now();
    for (0..n) |_| x = Fp.redcPortable(Fp.mulWide(x.l, y.l));
    report("fp mulWide+redcPortable", n, t0);
    t0 = now();
    for (0..n) |_| x = Fp.redcPortable(Fp.mulWidePortable(x.l, y.l));
    report("fp mulWideP+redcP", n, t0);
    t0 = now();
    for (0..n) |_| x = Fp.redcPortable(Fp.sqrWide(x.l));
    report("fp sqrWide+redcPortable", n, t0);
    t0 = now();
    for (0..n) |_| x = x.mul(y);
    report("fp mul (again)", n, t0);
    var z = y;
    t0 = now();
    for (0..n) |_| {
        x = x.sqr();
        z = z.sqr();
    }
    report("fp sqr x2 interleaved", n, t0);
    t0 = now();
    for (0..n) |_| {
        x = Fp.redc(Fp.sqrWide(x.l));
        z = Fp.redc(Fp.sqrWide(z.l));
    }
    report("fp sqrWide+redc x2", n, t0);
    std.mem.doNotOptimizeAway(&z);
    t0 = now();
    for (0..n) |_| x = x.add(y);
    report("fp add", n, t0);
    // the two carry forms `field.big_carry` picks between (it is false: per limb everywhere)
    inline for (.{ false, true }) |big| {
        const C = Fp.CarryForm(big);
        const tag = if (big) "big-int " else "per-limb";
        t0 = now();
        for (0..n) |_| x = C.add(x, y);
        report("fp add " ++ tag, n, t0);
        t0 = now();
        for (0..n) |_| x = C.sub(x, y);
        report("fp sub " ++ tag, n, t0);
        var wa = Fp.mulWide(x.l, y.l);
        const wb = Fp.mulWide(y.l, y.l);
        t0 = now();
        for (0..n) |_| wa = C.addWideModMR(wa, wb);
        report("fp wide add mod mR " ++ tag, n, t0);
        t0 = now();
        for (0..n) |_| wa = C.subWideModMR(wa, wb);
        report("fp wide sub mod mR " ++ tag, n, t0);
        std.mem.doNotOptimizeAway(&wa);
    }
    var x2 = curve.g2_generator.x;
    const y2 = curve.g2_generator.y;
    t0 = now();
    for (0..n) |_| x2 = x2.mul(y2);
    report("fp2 mul", n, t0);
    t0 = now();
    for (0..n) |_| x2 = x2.sqr();
    report("fp2 sqr", n, t0);
    t0 = now();
    for (0..1000) |_| x = x.inv();
    report("fp inv", 1000, t0);
    t0 = now();
    for (0..10000) |_| x = x.add(y).invVartime();
    report("fp inv vartime", 10000, t0);
    t0 = now();
    for (0..10000) |_| x = x.add(y).invEuclid();
    report("fp inv euclid (old)", 10000, t0);
    t0 = now();
    for (0..10000) |_| x = Fp.invDivsteps(x.add(y)).?;
    report("fp inv divsteps unchecked", 10000, t0);
    var s = field.Fr.fromU64(0x1234567);
    const s1 = field.Fr.fromU64(977);
    t0 = now();
    for (0..10000) |_| s = s.add(s1).invVartime();
    report("fr inv vartime", 10000, t0);
    t0 = now();
    for (0..10000) |_| s = s.add(s1).invEuclid();
    report("fr inv euclid (old)", 10000, t0);
    std.mem.doNotOptimizeAway(&s);
    t0 = now();
    for (0..1000) |_| x = encoding.sqrtFp(x.sqr()).?;
    report("fp sqrt", 1000, t0);
    t0 = now();
    for (0..1000) |_| x2 = x2.sqr().sqrt().?;
    report("fp2 sqrt", 1000, t0);
    var f = pairing.millerLoop(&.{.{ .p = curve.g1_generator, .q = curve.g2_generator }}, &.{});
    var f2 = f;
    t0 = now();
    for (0..10000) |_| f2 = f2.mul(f);
    report("fp12 mul", 10000, t0);
    t0 = now();
    for (0..10000) |_| f2 = f2.sqr();
    report("fp12 sqr", 10000, t0);
    t0 = now();
    for (0..10000) |_| f2 = f2.cyclotomicSqr();
    report("fp12 cyclo sqr", 10000, t0);
    std.mem.doNotOptimizeAway(&f2);
    var lines: [pairing.n_lines]pairing.Line = undefined;
    t0 = now();
    for (0..1000) |_| pairing.precomputeLines(curve.g2_generator, &lines);
    report("precompute lines", 1000, t0);
    const msg = "a checkpoint summary message of roughly the right length, padded out to ~200 bytes................................................................................................";
    var hp = h2c.hashToG1(msg, sig.min_sig_dst);
    t0 = now();
    for (0..1000) |i| hp = h2c.hashToG1(msg[0 .. 100 + i % 50], sig.min_sig_dst);
    report("hashToG1 (jacobian)", 1000, t0);
    var ha = hp.toAffine();
    t0 = now();
    for (0..1000) |_| ha = hp.toAffine();
    report("g1 toAffine", 1000, t0);
    var ok = true;
    t0 = now();
    for (0..1000) |_| ok = ok and curve.g1AffineInGroup(ha);
    report("g1 group check", 1000, t0);
    const sb = encoding.g1Compress(ha);
    t0 = now();
    for (0..1000) |_| ok = ok and (sig.Signature.decode(&sb) != null);
    report("sig decompress", 1000, t0);
    const pkb = encoding.g2Compress(curve.g2_generator);
    t0 = now();
    for (0..1000) |_| ok = ok and (sig.PublicKey.decode(&pkb) != null);
    report("pk decompress", 1000, t0);
    var acc = curve.G2.Point.infinity;
    t0 = now();
    for (0..10000) |_| acc = acc.addAffine(curve.g2_generator);
    report("g2 addAffine", 10000, t0);
    var aa = acc.toAffine();
    t0 = now();
    for (0..1000) |_| aa = acc.toAffine();
    report("g2 toAffine", 1000, t0);
    t0 = now();
    for (0..1000) |_| f = pairing.millerLoop(&.{.{ .p = ha, .q = aa }}, &.{.{ .p = ha.neg(), .lines = &lines }});
    report("miller loop 1+1pre", 1000, t0);
    t0 = now();
    for (0..1000) |_| f = pairing.finalExp(f);
    report("final exp", 1000, t0);
    t0 = now();
    for (0..1000) |_| f = pairing.millerLoop(&.{ .{ .p = ha, .q = aa }, .{ .p = ha.neg(), .q = curve.g2_generator } }, &.{});
    report("miller loop 2", 1000, t0);
    var f6 = f.c0;
    t0 = now();
    for (0..10000) |_| f6 = f6.mul(f.c1);
    report("fp6 mul", 10000, t0);
    t0 = now();
    for (0..10000) |_| f6 = f6.sqr();
    report("fp6 sqr", 10000, t0);
    t0 = now();
    for (0..10000) |_| f2 = f2.mulByLine(x2, y2, aa.x);
    report("fp12 mulByLine", 10000, t0);
    var hq = h2c.hashToG2(msg, "BLS_SIG_BLS12381G2_XMD:SHA-256_SSWU_RO_NUL_");
    t0 = now();
    for (0..1000) |i| hq = h2c.hashToG2(msg[0 .. 100 + i % 50], "BLS_SIG_BLS12381G2_XMD:SHA-256_SSWU_RO_NUL_");
    report("hashToG2 (jacobian)", 1000, t0);
    const qa = hq.toAffine();
    t0 = now();
    for (0..1000) |_| ok = ok and curve.g2AffineInGroup(qa);
    report("g2 group check", 1000, t0);
    const sb2 = encoding.g2Compress(qa);
    t0 = now();
    for (0..1000) |_| ok = ok and (encoding.g2FromBytes(&sb2) == .ok);
    report("g2 decompress (hashed pt)", 1000, t0);
    std.mem.doNotOptimizeAway(&f6);
    std.mem.doNotOptimizeAway(&f2);
    std.mem.doNotOptimizeAway(&f);
    std.mem.doNotOptimizeAway(&x);
    std.mem.doNotOptimizeAway(&x2);
    std.mem.doNotOptimizeAway(&ok);
}
