//! deepwave-validator (unaudited). Every command runs the safety gate first (gate.zig).
//!
//!   deepwave-validator gate-check --chain-id <8 hex> --address <addr>... [--key-file] [--unaudited-validator-i-accept-the-risk]
//!       prints the gate's decision and exits 0 (allowed) or 1 (refused).
//!   deepwave-validator run (--localnet DIR --index N | --config FILE --chain-id HEX8) [...]
//!       validator mode (node.zig, val-epoch-api-keys): gate, signer, epoch lifecycle, lane hooks,
//!       the Validator gRPC API and metrics. `deepwave validator ...` hands over to this command.
//!   deepwave-validator vectors-check DIR     compare with tools/truth/validator-epoch vectors
//!   deepwave-validator localnet DIR --validators N [--seed HEX64] [--base-port P] [--epoch-ms MS]
//!       writes a local test committee (localnet.json and validator-<i>.yaml).
//!   deepwave-validator budget --demo [--txs N] | <dump-file>   latency budget table (no gate, no keys)
//!   deepwave-validator preverify-bench [--lanes N] [--sizes ...] [--mixed]   signature pre-verification
//!       off vs on over synthetic blocks and submit requests (no gate, no keys)
//!   deepwave-validator seat --config FILE [...]
//!       consensus only, in one seat of a local committee generated by Mysten's `sui genesis`
//!       (seat.zig; docs/VALIDATOR-MIXED-LOCALNET.md).
const std = @import("std");
const validator = @import("validator");
const gate = validator.gate;

pub fn main(init: std.process.Init) !u8 {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len < 2) return usage();
    const cmd = args[1];
    // The latency budget table needs no keys and no network: it runs before the gate.
    if (std.mem.eql(u8, cmd, "budget")) return validator.latency.cli.run(init.io, init.gpa, args[2..]);
    // Signature pre-verification benchmark: synthetic local transactions, no keys, no network.
    if (std.mem.eql(u8, cmd, "preverify-bench")) return validator.authority.preverify_fixture.benchMain(init.gpa, init.io, args[2..]);
    if (std.mem.eql(u8, cmd, "run")) return validator.node.run(init.gpa, init.io, args[2..]);
    if (std.mem.eql(u8, cmd, "localnet")) return localnetCmd(init, args[2..]);
    if (std.mem.eql(u8, cmd, "seat")) return validator.seat.run(init.gpa, init.io, args[2..]);
    if (std.mem.eql(u8, cmd, "vectors-check") and args.len == 3) {
        const rep = validator.epoch.vectors.check(init.gpa, init.io, args[2]) catch |e| {
            std.debug.print("deepwave-validator: vectors-check: {s}\n", .{@errorName(e)});
            return 1;
        };
        std.debug.print("vectors-check: {d} ok, {d} failed, {d} missing\n", .{ rep.ok, rep.failed, rep.missing });
        return if (rep.failed == 0 and rep.missing == 0) 0 else 1;
    }
    var chain_id: []const u8 = "";
    var addrs: std.ArrayList([]const u8) = .empty;
    var key_source: gate.KeySource = .generated;
    var flag = false;
    var i: usize = 2;
    while (i < args.len) : (i += 1) {
        const a = args[i];
        if (std.mem.eql(u8, a, "--chain-id") and i + 1 < args.len) {
            i += 1;
            chain_id = args[i];
        } else if (std.mem.eql(u8, a, "--address") and i + 1 < args.len) {
            i += 1;
            try addrs.append(init.arena.allocator(), args[i]);
        } else if (std.mem.eql(u8, a, "--key-file")) {
            key_source = .file;
        } else if (std.mem.eql(u8, a, gate.unaudited_runtime_flag)) {
            flag = true;
        } else return usage();
    }
    const decision = gate.decide(.{ .chain_id = chain_id, .addresses = addrs.items, .key_source = key_source, .unaudited_flag = flag });
    switch (decision) {
        .refused => |r| {
            std.debug.print("deepwave-validator: {s}\n", .{r.text()});
            return 1;
        },
        .allowed => |l| std.debug.print("deepwave-validator: allowed ({s}) on chain {s}\n", .{ @tagName(l.mode), &l.chain_id }),
    }
    if (std.mem.eql(u8, cmd, "gate-check")) return 0;
    return usage();
}

fn localnetCmd(init: std.process.Init, args: []const []const u8) u8 {
    if (args.len < 1) return usage();
    const dir = args[0];
    var n: u32 = 4;
    var seed: [32]u8 = undefined;
    init.io.random(&seed);
    var opts: validator.keys.localnet.Options = .{};
    var i: usize = 1;
    while (i < args.len) : (i += 1) {
        const a = args[i];
        const has = i + 1 < args.len;
        if (std.mem.eql(u8, a, "--validators") and has) {
            i += 1;
            n = std.fmt.parseInt(u32, args[i], 10) catch return usage();
        } else if (std.mem.eql(u8, a, "--seed") and has) {
            i += 1;
            if (args[i].len != 64) return usage();
            _ = std.fmt.hexToBytes(&seed, args[i]) catch return usage();
        } else if (std.mem.eql(u8, a, "--base-port") and has) {
            i += 1;
            opts.base_port = std.fmt.parseInt(u16, args[i], 10) catch return usage();
        } else if (std.mem.eql(u8, a, "--epoch-ms") and has) {
            i += 1;
            opts.epoch_duration_ms = std.fmt.parseInt(u64, args[i], 10) catch return usage();
        } else return usage();
    }
    validator.keys.localnet.Localnet.generate(init.gpa, init.io, dir, n, seed, opts) catch |e| {
        std.debug.print("deepwave-validator: localnet failed: {s}\n", .{@errorName(e)});
        return 1;
    };
    std.debug.print("deepwave-validator: wrote {d} validators to {s}\n", .{ n, dir });
    return 0;
}

fn usage() u8 {
    std.debug.print("usage: deepwave-validator gate-check --chain-id <8 hex> --address <addr>... [--key-file] [{s}]\n", .{gate.unaudited_runtime_flag});
    std.debug.print("{s}", .{validator.node.usage});
    std.debug.print("{s}", .{validator.seat.usage});
    return 2;
}
