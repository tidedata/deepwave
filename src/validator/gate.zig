//! The validator safety gate (docs/VALIDATOR-DESIGN.md section 8). validator-base owns this file.
//!
//! deepwave's validator code is unaudited. It must never sign anything on mainnet or testnet. The
//! gate decides once, at startup, before any key is opened, socket bound or peer dialed:
//!
//!   allowed (local_test)  the chain is neither mainnet nor testnet, every committee address is
//!                         loopback or private (RFC 1918 / ULA / localhost), and every key was
//!                         generated for this local committee (never loaded from a key file);
//!   allowed (unaudited)   the binary was built with -Dvalidator-unaudited=true AND the operator
//!                         passed the runtime flag `--unaudited-validator-i-accept-the-risk`;
//!   refused               everything else, with the reason.
//!
//! The decision is a `License`. The signer (signer.zig) only opens with a valid license and
//! binds every signature to the license's chain id, so a later code path cannot skip the gate.
//! With the build option off (the default), the unaudited branch is compiled out entirely.
const std = @import("std");
const build_options = @import("validator_options");

/// -Dvalidator-unaudited (default false).
pub const unaudited_build: bool = build_options.validator_unaudited;
/// The runtime flag that, together with the build option, allows a non-local network.
pub const unaudited_runtime_flag = "--unaudited-validator-i-accept-the-risk";

/// sui ChainIdentifier: the first 4 bytes of the genesis checkpoint digest, hex.
pub const mainnet_chain_id = "35834a8a";
pub const testnet_chain_id = "4c78adac";

pub const KeySource = enum {
    /// Generated in-process for a local test committee (deepwave-validator localnet).
    generated,
    /// Loaded from a key file or validator.yaml.
    file,
    /// The keys of one seat of a local committee generated by Mysten's own tooling (`sui genesis`),
    /// read from that seat's validator.yaml. Only `deepwave-validator seat` uses it, after checking that
    /// the keys are a member of the genesis committee and every genesis address is local. Allowed in
    /// local_test mode like `generated` (mixed Mysten/zui localnets, docs/VALIDATOR-MIXED-LOCALNET.md).
    localnet_config,
};

pub const Request = struct {
    /// Chain identifier of the genesis this validator would join (8 hex characters).
    chain_id: []const u8,
    /// Every address this validator would bind or dial: consensus, p2p and validator gRPC
    /// addresses of all committee members (multiaddr text such as "/ip4/127.0.0.1/tcp/8080",
    /// "/dns/localhost/udp/8084", or "host:port").
    addresses: []const []const u8,
    key_source: KeySource,
    /// The operator passed `unaudited_runtime_flag`.
    unaudited_flag: bool = false,
};

pub const Mode = enum { local_test, unaudited };

pub const Refusal = enum {
    mainnet,
    testnet,
    bad_chain_id,
    empty_committee,
    non_local_address,
    bad_address,
    key_file_in_local_mode,
    unaudited_build_off,

    pub fn text(r: Refusal) []const u8 {
        return switch (r) {
            .mainnet => "refused: chain is Sui mainnet; zui validator code is unaudited and never signs on mainnet",
            .testnet => "refused: chain is Sui testnet; zui validator code is unaudited and never signs on testnet",
            .bad_chain_id => "refused: chain id is not 8 hex characters",
            .empty_committee => "refused: no committee addresses given",
            .non_local_address => "refused: a committee address is not loopback or private; local test committees only",
            .bad_address => "refused: a committee address could not be parsed",
            .key_file_in_local_mode => "refused: local test committees use generated keys only, never key files",
            .unaudited_build_off => "refused: --unaudited-validator-i-accept-the-risk needs a build with -Dvalidator-unaudited=true",
        };
    }
};

/// Proof that the gate allowed validator mode. Only `decide` makes valid ones.
pub const License = struct {
    mode: Mode,
    chain_id: [8]u8,
    seal: u64,

    pub fn valid(l: *const License) bool {
        return issued.load(.acquire) and l.seal == sealOf(l.mode, &l.chain_id);
    }
};

pub const Decision = union(enum) {
    allowed: License,
    refused: Refusal,
};

var issued: std.atomic.Value(bool) = .init(false);
const seal_key: u64 = 0x7a75_692d_6761_7465; // "zui-gate"

fn sealOf(mode: Mode, chain_id: *const [8]u8) u64 {
    var h = std.hash.Wyhash.init(seal_key);
    h.update(&.{@intFromEnum(mode)});
    h.update(chain_id);
    return h.final();
}

fn issue(mode: Mode, chain_id: *const [8]u8) Decision {
    issued.store(true, .release);
    return .{ .allowed = .{ .mode = mode, .chain_id = chain_id.*, .seal = sealOf(mode, chain_id) } };
}

pub fn decide(req: Request) Decision {
    if (req.chain_id.len != 8) return .{ .refused = .bad_chain_id };
    var cid: [8]u8 = undefined;
    for (req.chain_id, 0..) |c, i| {
        if (!std.ascii.isHex(c)) return .{ .refused = .bad_chain_id };
        cid[i] = std.ascii.toLower(c);
    }
    if (unaudited_build and req.unaudited_flag) return issue(.unaudited, &cid);

    if (std.mem.eql(u8, &cid, mainnet_chain_id)) return .{ .refused = .mainnet };
    if (std.mem.eql(u8, &cid, testnet_chain_id)) return .{ .refused = .testnet };
    // Asking for unaudited mode on a build without the option is an operator error worth
    // stopping on, whatever the committee looks like.
    if (req.unaudited_flag and !unaudited_build) return .{ .refused = .unaudited_build_off };
    if (req.addresses.len == 0) return .{ .refused = .empty_committee };
    for (req.addresses) |a| switch (classify(a)) {
        .local => {},
        .public => return .{ .refused = .non_local_address },
        .invalid => return .{ .refused = .bad_address },
    };
    if (req.key_source == .file) return .{ .refused = .key_file_in_local_mode };
    return issue(.local_test, &cid);
}

pub const AddressClass = enum { local, public, invalid };

/// Classifies one address. Accepts multiaddr text (/ip4, /ip6, /dns, /dns4, /dns6 with any
/// trailing protocol parts) and "host:port". DNS names are local only when they are
/// "localhost" (a name could resolve anywhere).
pub fn classify(addr: []const u8) AddressClass {
    if (addr.len == 0) return .invalid;
    if (addr[0] == '/') {
        var it = std.mem.tokenizeScalar(u8, addr, '/');
        const proto = it.next() orelse return .invalid;
        const host = it.next() orelse return .invalid;
        if (std.mem.eql(u8, proto, "ip4")) return classifyIp4(host);
        if (std.mem.eql(u8, proto, "ip6")) return classifyIp6(host);
        if (std.mem.eql(u8, proto, "dns") or std.mem.eql(u8, proto, "dns4") or std.mem.eql(u8, proto, "dns6"))
            return if (std.ascii.eqlIgnoreCase(host, "localhost")) .local else .public;
        return .invalid;
    }
    // host:port, [v6]:port
    if (addr[0] == '[') {
        const end = std.mem.indexOfScalar(u8, addr, ']') orelse return .invalid;
        return classifyIp6(addr[1..end]);
    }
    const colon = std.mem.lastIndexOfScalar(u8, addr, ':') orelse return .invalid;
    const host = addr[0..colon];
    if (std.ascii.eqlIgnoreCase(host, "localhost")) return .local;
    return classifyIp4(host);
}

fn classifyIp4(s: []const u8) AddressClass {
    var o: [4]u8 = undefined;
    var it = std.mem.splitScalar(u8, s, '.');
    var n: usize = 0;
    while (it.next()) |part| : (n += 1) {
        if (n == 4) return .invalid;
        o[n] = std.fmt.parseInt(u8, part, 10) catch return .invalid;
    }
    if (n != 4) return .invalid;
    if (o[0] == 127 or o[0] == 10) return .local;
    if (o[0] == 172 and o[1] >= 16 and o[1] <= 31) return .local;
    if (o[0] == 192 and o[1] == 168) return .local;
    return .public;
}

fn classifyIp6(s: []const u8) AddressClass {
    if (s.len < 2 or std.mem.indexOfScalar(u8, s, ':') == null) return .invalid;
    for (s) |c| if (!(std.ascii.isHex(c) or c == ':')) return .invalid;
    if (std.mem.eql(u8, s, "::1")) return .local;
    // fc00::/7 (unique local): the first hextet is written with 4 digits fcXX or fdXX
    // ("fc::1" is 00fc::1, public).
    const first_end = std.mem.indexOfScalar(u8, s, ':').?;
    const c0 = std.ascii.toLower(s[0]);
    const c1 = std.ascii.toLower(s[1]);
    if (first_end == 4 and c0 == 'f' and (c1 == 'c' or c1 == 'd')) return .local;
    return .public;
}

// ------------------------------------------------------------------------------------- tests

const local_addrs = [_][]const u8{ "/ip4/127.0.0.1/tcp/8080", "/ip4/192.168.0.9/udp/8084", "/dns/localhost/tcp/1", "127.0.0.1:9000", "[::1]:8080", "/ip6/fd12:3456::1/tcp/1" };

test "mainnet and testnet are always refused without the unaudited build" {
    const m = decide(.{ .chain_id = mainnet_chain_id, .addresses = &local_addrs, .key_source = .generated });
    try std.testing.expectEqual(Refusal.mainnet, m.refused);
    const t = decide(.{ .chain_id = "4C78ADAC", .addresses = &local_addrs, .key_source = .generated });
    try std.testing.expectEqual(Refusal.testnet, t.refused);
    if (!unaudited_build) {
        const f = decide(.{ .chain_id = mainnet_chain_id, .addresses = &local_addrs, .key_source = .file, .unaudited_flag = true });
        try std.testing.expectEqual(Refusal.mainnet, f.refused);
    }
}

test "local test committee is allowed with generated keys only" {
    const ok = decide(.{ .chain_id = "0badc0de", .addresses = &local_addrs, .key_source = .generated });
    try std.testing.expect(ok == .allowed);
    try std.testing.expect(ok.allowed.valid());
    try std.testing.expectEqual(Mode.local_test, ok.allowed.mode);
    const files = decide(.{ .chain_id = "0badc0de", .addresses = &local_addrs, .key_source = .file });
    try std.testing.expectEqual(Refusal.key_file_in_local_mode, files.refused);
}

test "a Mysten-generated local seat is allowed only on a local chain with local addresses" {
    const ok = decide(.{ .chain_id = "0badc0de", .addresses = &local_addrs, .key_source = .localnet_config });
    try std.testing.expectEqual(Mode.local_test, ok.allowed.mode);
    try std.testing.expectEqual(Refusal.mainnet, decide(.{ .chain_id = mainnet_chain_id, .addresses = &local_addrs, .key_source = .localnet_config }).refused);
    try std.testing.expectEqual(Refusal.testnet, decide(.{ .chain_id = testnet_chain_id, .addresses = &local_addrs, .key_source = .localnet_config }).refused);
    const addrs = [_][]const u8{ "/ip4/127.0.0.1/udp/1", "/ip4/8.8.8.8/udp/8081" };
    try std.testing.expectEqual(Refusal.non_local_address, decide(.{ .chain_id = "0badc0de", .addresses = &addrs, .key_source = .localnet_config }).refused);
}

test "any public address refuses local mode" {
    const addrs = [_][]const u8{ "/ip4/127.0.0.1/tcp/1", "/ip4/8.8.8.8/tcp/8080" };
    try std.testing.expectEqual(Refusal.non_local_address, decide(.{ .chain_id = "0badc0de", .addresses = &addrs, .key_source = .generated }).refused);
    const dns = [_][]const u8{"/dns/validator.example.com/tcp/8080"};
    try std.testing.expectEqual(Refusal.non_local_address, decide(.{ .chain_id = "0badc0de", .addresses = &dns, .key_source = .generated }).refused);
    const none = [_][]const u8{};
    try std.testing.expectEqual(Refusal.empty_committee, decide(.{ .chain_id = "0badc0de", .addresses = &none, .key_source = .generated }).refused);
    const bad = [_][]const u8{"/ip4/300.1.1.1/tcp/1"};
    try std.testing.expectEqual(Refusal.bad_address, decide(.{ .chain_id = "0badc0de", .addresses = &bad, .key_source = .generated }).refused);
}

test "unaudited flag needs the build option" {
    const d = decide(.{ .chain_id = "0badc0de", .addresses = &local_addrs, .key_source = .generated, .unaudited_flag = true });
    if (unaudited_build) {
        try std.testing.expectEqual(Mode.unaudited, d.allowed.mode);
    } else {
        try std.testing.expectEqual(Refusal.unaudited_build_off, d.refused);
    }
}

test "a hand-made license is not valid" {
    const forged: License = .{ .mode = .unaudited, .chain_id = mainnet_chain_id.*, .seal = 1 };
    try std.testing.expect(!forged.valid());
}

test "address classes" {
    try std.testing.expectEqual(AddressClass.local, classify("/ip4/10.1.2.3/tcp/1"));
    try std.testing.expectEqual(AddressClass.local, classify("/ip4/172.20.0.1/tcp/1"));
    try std.testing.expectEqual(AddressClass.public, classify("/ip4/172.32.0.1/tcp/1"));
    try std.testing.expectEqual(AddressClass.public, classify("/ip6/2001:db8::1/tcp/1"));
    try std.testing.expectEqual(AddressClass.public, classify("/ip6/fc::1/tcp/1"));
    try std.testing.expectEqual(AddressClass.local, classify("/ip6/fd00::1/tcp/1"));
    try std.testing.expectEqual(AddressClass.invalid, classify("/tcp/1"));
    try std.testing.expectEqual(AddressClass.invalid, classify(""));
    try std.testing.expectEqual(AddressClass.public, classify("1.2.3.4:80"));
}
