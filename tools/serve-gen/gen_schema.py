#!/usr/bin/env python3
"""Generates src/serve/schema.zig (message field tables for read_mask validation) from the
sui-rpc generated field_info.rs (the table FieldMaskUtil::validate walks)."""
import re, sys, glob, os
src = sys.argv[1]
out = sys.argv[2]
text = open(src).read()
consts = {}  # (msg, CONST) -> (name, sub)
for m in re.finditer(r'impl (\w+) \{\s*((?:pub const \w+_FIELD: &\'static MessageField = &MessageField \{.*?\};\s*)+)\}', text, re.S):
    msg = m.group(1)
    for c in re.finditer(r'pub const (\w+): &\'static MessageField = &MessageField \{\s*name: "(\w+)",.*?message_fields: (None|Some\((\w+)::FIELDS\)),', m.group(2), re.S):
        consts[(msg, c.group(1))] = (c.group(2), c.group(4))
msgs = {}
for m in re.finditer(r'impl MessageFields for (\w+) \{\s*const FIELDS: &\'static \[&\'static MessageField\] = &\[(.*?)\];', text, re.S):
    msg = m.group(1)
    fields = []
    for f in re.finditer(r'Self::(\w+)', m.group(2)):
        fields.append(consts[(msg, f.group(1))])
    msgs[msg] = fields
names = sorted(msgs)
idx = {n: i for i, n in enumerate(names)}
with open(out, 'w') as o:
    o.write('//! GENERATED by tools/serve-gen/gen_schema.py from sui-rpc field_info.rs. Do not edit.\n')
    o.write('//! Message field tables for read_mask validation (FieldMaskUtil::validate).\n\n')
    o.write('pub const Field = struct { name: []const u8, sub: i16 };\n')
    o.write('pub const Message = struct { name: []const u8, fields: []const Field };\n\n')
    o.write('pub const messages = [_]Message{\n')
    for n in names:
        o.write('    .{ .name = "%s", .fields = &.{\n' % n)
        for (fname, sub) in msgs[n]:
            o.write('        .{ .name = "%s", .sub = %d },\n' % (fname, idx[sub] if sub else -1))
        o.write('    } },\n')
    o.write('};\n\n')
    o.write('pub fn index(comptime name: []const u8) i16 {\n    inline for (messages, 0..) |m, i| if (comptime std.mem.eql(u8, m.name, name)) return i;\n    @compileError("no message " ++ name);\n}\n\n')
    o.write('const std = @import("std");\n')
